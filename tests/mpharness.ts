import { chunker, joiner } from '../src/net/rtc';
import { createHash } from 'node:crypto';

/** Stable fixture identity in the same 16-hex format generated by the app. */
export const testPeerKey = (label: string) => /^[0-9a-f]{16}$/i.test(label) ? label : createHash('sha256').update(label).digest('hex').slice(0, 16);

export class Peer implements SimPort {
  ns: NetSim | null = null; session!: Session; reports: { tick: number; hostTick: number; local: string; host: string }[] = [];
  acc = 0; skew = 1; early: TickFrame[] = []; earlyF: Frame[] = []; loads = 0;
  constructor(public g: Game) {}
  frame(f: Frame) { if (this.ns) this.ns.ls.receive(f); else this.earlyF.push(f); }
  tick(f: TickFrame) { if (this.ns) this.ns.ls.receiveTick(f); else this.early.push(f); }
  setDelay(d: number) { if (this.ns) this.ns.ls.delay = d; }
  pause(on: boolean) { if (this.ns && this.session.isHost) this.ns.paused = on; }
  want(p: number) { this.ns?.ls.wantPl(p); }
  drop(p: number) { this.ns?.ls.dropPl(p); }
  inject(c: Command[], o: { save?: boolean; pause?: boolean }, cb?: (s: { tick: number; data: string }) => void) { this.ns!.inject(c, o, cb); }
  resync(tick: number, data: string) {
    this.ns!.catchUp(tick); const own = this.ns!.lastSnap;
    if (this.session.isHost) { const g2 = deserialize(JSON.parse(data)); this.g = g2; this.ns!.reset(g2); return; }
    if (this.session.desyncs > this.reports.length) this.reports.push({ tick: own?.tick ?? this.g.tick, hostTick: tick, local: own && own.tick === tick ? own.data : this.g.tick === tick ? JSON.stringify(serialize(this.g)) : '', host: data });
    const g2 = deserialize(JSON.parse(data)); this.g = g2; this.ns!.reset(g2);
  }
  async prepare(map: MapCfg, players: { name: string; color: string; key: string }[]) {
    const r = prepareWorld(this.g, map, players); this.g = r.g;
    this.prepared = JSON.stringify(serialize(this.g)); return { tick: this.g.tick, data: this.prepared, pls: r.pls, peers: r.peers };
  }
  prepared = '';
  start(o: StartInfo) {
    // хост тоже загружает мир из той же строки, что ушла клиентам: старт у всех из одного состояния
    this.g = deserialize(JSON.parse(o.data || this.prepared)); this.loads++;
    const ns = new NetSim(this.g, o.n, o.me, o.delay, o.host); this.ns = ns; for (const p of o.need || []) ns.ls.need.add(p);
    ns.onFrame = f => this.session.onSimFrame(f); ns.onTick = f => this.session.onSimTick(f);
    ns.onHash = (t, h) => { this.hashes.set(t, h); if (this.fullEvery && t % this.fullEvery === 0) this.full.set(t, stateHash(this.g)); this.session.onSimHash(t, h); };
    for (const f of this.early.splice(0)) ns.ls.receiveTick(f); for (const f of this.earlyF.splice(0)) ns.ls.receive(f);
  }
  handoff(cb: (from: number, frames: Frame[]) => void) { const ls = this.ns!.ls; const from = ls.next; cb(from, ls.becomeClient(from)); }
  becomeHost(from: number, need: number[]) { this.ns!.becomeHost(from, need); }
  resend() { this.ns?.resend(); }
  hashes = new Map<number, string>(); full = new Map<number, string>(); fullEvery = 0;
  cmd(c: Command) { this.ns?.cmd(c); }
  /** номер своего персонажа */ get me() { return this.ns?.ls.me ?? this.session.me; }
}

export interface CoopOpts { n: number; pingMs: number; jitterMs?: number; loss: number; seed: number; enemies?: string; map?: 'new' | 'current'; game?: Game; names?: string[]; kbps?: number; }
export class Coop {
  now = 0; net: FakeNet; peers: Peer[] = []; host: Session; links = new Map<Session, Map<Session, number>>();
  constructor(public o: CoopOpts) {
    this.net = new FakeNet(o.pingMs / 2, o.jitterMs ?? Math.min(20, o.pingMs / 10), o.loss, o.seed, o.kbps);
    const clock = () => this.now;
    const hp = new Peer(o.game || new Game(o.seed, true, { enemies: (o.enemies || 'none') as any })); this.peers.push(hp);
    this.host = new Session('host', hp, clock, o.names?.[0] || 'Хост', '#d2782e', testPeerKey('key-0')); hp.session = this.host; this.hook(hp);
    this.host.setMap({ mode: o.map || 'new', seed: o.seed, enemies: o.enemies || 'none' });
    for (let i = 1; i < o.n; i++) this.addClient(o.names?.[i] || 'Игрок ' + (i + 1), 'key-' + i);
  }
  /** соединение a ↔ b через эмуляцию сети */
  connect(a: Session, b: Session) {
    const clock = () => this.now; let ia = 0, ib = 0;
    // как в браузере: длинные строки режутся на куски по 16 000 знаков и склеиваются заново (v1.14.1: до этого тесты этот слой обходили — и не видели, что мир больше ~12 КБ не доходит)
    const ja = joiner(s => b.rawIn(ib, s)), jb = joiner(s => a.rawIn(ia, s));
    ia = a.attach(chunker(this.net.pipe(clock, s => ja(s)))); ib = b.attach(chunker(this.net.pipe(clock, s => jb(s))));
    const m = this.links.get(a) || new Map(); m.set(b, ia); this.links.set(a, m); const n = this.links.get(b) || new Map(); n.set(a, ib); this.links.set(b, n);
    return [ia, ib];
  }
  /** обрыв соединения a ↔ b (у обоих) */
  cut(a: Session, b: Session) { const ia = this.links.get(a)?.get(b), ib = this.links.get(b)?.get(a); if (ia !== undefined) a.closed(ia); if (ib !== undefined) b.closed(ib); this.links.get(a)?.delete(b); this.links.get(b)?.delete(a); }
  /** новый игрок: подключается к текущему хосту (в лобби или в идущую игру) */
  addClient(name: string, key: string, game = new Game(1, false)) {
    const p = new Peer(game); this.peers.push(p);
    const s = new Session('client', p, () => this.now, name, '', testPeerKey(key)); p.session = s; this.hook(p);
    this.connect(this.hostSession(), s); return p;
  }
  /** игрок закрыл вкладку и открыл снова: новая сессия с тем же ключом */
  reconnect(p: Peer, name = p.session['myName' as keyof Session] as any as string) {
    const key = p.session.key; this.cut(this.hostSession(), p.session); p.ns = null; p.early = []; p.earlyF = [];
    const s = new Session('client', p, () => this.now, name, '', key); p.session = s; this.hook(p); this.connect(this.hostSession(), s); return p;
  }
  hostSession() { return this.peers.find(p => p.session.isHost && p.session.state !== 'closed')!.session; }
  hostPeer() { return this.peers.find(p => p.session.isHost && p.session.state !== 'closed')!; }
  /** передача хоста: новый хост просит соединений с остальными — здесь они создаются напрямую */
  private hook(p: Peer) {
    p.session.onEvent = (e, d) => {
      if (e === 'xconnect') for (const pl of d.pls as number[]) { const q = this.peers.find(x => x.session.state === 'game' && x.me === pl && x !== p); if (q) this.connect(p.session, q.session); }
      this.events.push([this.peers.indexOf(p), e, d]);
    };
  }
  events: [number, string, any][] = [];
  /** продвинуть виртуальное время на ms (шаг 4 мс, как таймер Worker'а); before — перед каждым тиком игрока */
  advance(ms: number, before?: (p: Peer, i: number) => void) {
    const end = this.now + ms;
    while (this.now < end) {
      this.now += 4; this.net.run(this.now);
      if (this.now % 20 === 0) for (const p of this.peers) p.session.poll();
      for (let i = 0; i < this.peers.length; i++) {
        const p = this.peers[i]; if (!p.ns || p.session.state === 'closed') continue;
        p.acc += 4 * p.skew; let k = 0; const behind = p.ns.ls.buffered(p.g.tick) > 30; // догон: до ×10
        if (behind) p.acc += 4 * 9;
        while (p.acc >= 1000 / 60 && k++ < (behind ? 40 : 5)) { before?.(p, i); if (p.ns.tryTick()) p.acc -= 1000 / 60; else { p.acc = Math.min(p.acc, 1000 / 60 * 3); break; } }
      }
    }
  }
  /** лобби → «Готов» у всех → старт */
  async start() {
    this.advance(300);
    for (const p of this.peers.slice(1)) p.session.setReady(true);
    this.advance(300);
    if (!this.host.allReady()) throw new Error('лобби: не все готовы — ' + JSON.stringify(this.host.players));
    await this.host.startGame(); this.advance(400);
    for (let k = 0; k < 600 && this.peers.some(p => !p.ns); k++) this.advance(200); // большой мир — дольше
    if (this.peers.some(p => !p.ns)) throw new Error('старт: не все получили мир');
  }
  live() { return this.peers.filter(p => p.ns && p.session.state === 'game'); }
  ticks() { return this.peers.map(p => p.g.tick); }
  /** последняя общая точка сверки: quickHash у всех на одном тике */
  sameState(ps = this.live()): { ok: boolean; tick: number; hashes: string[] } {
    const common = [...ps[0].hashes.keys()].filter(t => ps.every(p => p.hashes.has(t)));
    const t = Math.max(...common, -1); const hashes = ps.map(p => p.hashes.get(t) || '');
    return { ok: t >= 0 && hashes.every(h => h === hashes[0]), tick: t, hashes };
  }
  fullHashAt(): string[] { return this.peers.map(p => stateHash(p.g)); }
}
